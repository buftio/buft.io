const ABC = '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz-_'
const SIDES = 10

export type Cell = { x: number; y: number; r: number[]; mean: number }

export function cells(): Cell[] {
  const v = (k: number) => ABC.indexOf(COMB[k])
  const out: Cell[] = []
  for (let i = 0; i + 4 + SIDES <= COMB.length; i += 4 + SIDES) {
    const r = Array.from({ length: SIDES }, (_, k) => v(i + 4 + k) * 5 + 3)
    out.push({
      x: (v(i) * 64 + v(i + 1)) * 2 - 2600,
      y: (v(i + 2) * 64 + v(i + 3)) * 2 - 2600,
      r,
      mean: r.reduce((a, b) => a + b, 0) / SIDES,
    })
  }
  return out
}
