export type Bubble = { x: number; y: number; r: number; near: number[] }

export const BUBBLES: Bubble[] = []
for (let k = 0; k < RAW.length; k += 3) BUBBLES.push({ x: RAW[k], y: RAW[k + 1], r: RAW[k + 2], near: [] })
BUBBLES.forEach((a, i) =>
  BUBBLES.forEach((b, j) => {
    if (i !== j && Math.hypot(a.x - b.x, a.y - b.y) < (a.r + b.r) * 1.3 + 90) a.near.push(j)
  }),
)

export const nearest = (x: number, y: number) => {
  let best = 0
  BUBBLES.forEach((b, k) => {
    if (Math.hypot(b.x - x, b.y - y) < Math.hypot(BUBBLES[best].x - x, BUBBLES[best].y - y)) best = k
  })
  return best
}

