const N = 24

export function rim(isle: Isle, a: number) {
  const f = ((((a / (Math.PI * 2)) % 1) + 1) % 1) * N
  const i = Math.floor(f) % N
  const t = f - Math.floor(f)
  return isle[2][i] * (1 - t) + isle[2][(i + 1) % N] * t
}

export const size = (isle: Isle) => isle[2].reduce((s, r) => s + r, 0) / N

export function onLand(x: number, y: number, pad = 0) {
  for (const isle of ISLES) {
    const dx = x - isle[0]
    const dy = y - isle[1]
    if (Math.hypot(dx, dy) < rim(isle, Math.atan2(dy, dx)) + pad) return true
  }
  return false
}

export function shore(isle: Isle, a: number, out = 0): [number, number] {
  const r = rim(isle, a) + out
  return [isle[0] + Math.cos(a) * r, isle[1] + Math.sin(a) * r]
}
